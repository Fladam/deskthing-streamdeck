// Embeds the single-file configurator build into the server bundle as a string.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const html = readFileSync(new URL("../.configurator-build/index.html", import.meta.url), "utf8");
const outDir = new URL("../server/generated/", import.meta.url);
mkdirSync(outDir, { recursive: true });
writeFileSync(
  new URL("configuratorHtml.ts", outDir),
  `// AUTO-GENERATED by scripts/embed-configurator.mjs. Do not edit.\nexport default ${JSON.stringify(html)};\n`
);
console.log(`Embedded configurator (${(html.length / 1024).toFixed(1)} KB)`);
